#!/usr/bin/env python3
"""Regenerate the species table that every test fixture reads (Tests/PokeTokenBarTests/SpeciesFactsData.swift).

    python3 scripts/generate-species-facts.py

Tests and screenshot renders never invent a species' types, stats, gender ratio or names; they ask
`SpeciesFacts` (Tests/PokeTokenBarTests/SpeciesFacts.swift), which reads this table. The table holds the
real PokéAPI values for the ids in SPECIES_IDS, and an id outside it fails the test with the command
to run. To use another species in a test, add its id below and re-run this script (PokéAPI is only
needed here, never at test time). Moves and abilities are not in the table: a test that needs them
passes them in.
"""
import json
import sys
import time
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

API = "https://pokeapi.co/api/v2"
OUT = Path(__file__).resolve().parent.parent / "Tests/PokeTokenBarTests/SpeciesFactsData.swift"
STAT_ORDER = ["hp", "attack", "defense", "special-attack", "special-defense", "speed"]

# Gen I, plus the species other fixtures use. Keep ascending.
SPECIES_IDS = sorted(set(range(1, 152)) | {
    106, 114, 172, 177, 178, 208, 236, 265, 266, 267, 287, 292, 382, 446, 447, 448, 492, 592, 593, 686, 687, 1017, 1024,
})


def main():
    with ThreadPoolExecutor(max_workers=6) as pool:
        rows = list(pool.map(fetch_row, SPECIES_IDS))
    lines = [
        "// Generated by scripts/generate-species-facts.py from PokéAPI. Do not edit by hand.",
        "",
        "extension SpeciesFacts {",
        "    static let table: [SpeciesFact] = [",
        *[f"        {row}," for row in rows],
        "    ]",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"{len(rows)} species -> {OUT}", file=sys.stderr)


def fetch_row(species_id):
    pokemon = get(f"{API}/pokemon/{species_id}")
    species = get(f"{API}/pokemon-species/{species_id}")
    names = {n["language"]["name"]: n["name"] for n in species["names"]}
    stats = {s["stat"]["name"]: s["base_stat"] for s in pokemon["stats"]}
    types = [t["type"]["name"] for t in sorted(pokemon["types"], key=lambda t: t["slot"])]
    parent = species["evolves_from_species"]
    parent_id = int(parent["url"].rstrip("/").split("/")[-1]) if parent else None
    return (
        f"SpeciesFact(id: {species_id}, slug: {swift(pokemon['name'])}, "
        f"en: {swift(names['en'])}, ko: {swift(names['ko'])}, "
        f"height: {pokemon['height']}, weight: {pokemon['weight']}, "
        f"baseExperience: {pokemon['base_experience']}, genderRate: {species['gender_rate']}, "
        f"types: {json.dumps(types)}, stats: {[stats[name] for name in STAT_ORDER]}, "
        f"captureRate: {species['capture_rate']}, isLegendary: {str(species['is_legendary']).lower()}, "
        f"isMythical: {str(species['is_mythical']).lower()}, "
        f"evolvesFromID: {parent_id if parent_id is not None else 'nil'})"
    )


def swift(text):
    return json.dumps(text, ensure_ascii=False)


def get(url):
    request = urllib.request.Request(url, headers={"User-Agent": "poketokenbar-fixture-dump"})
    for attempt in range(6):
        try:
            with urllib.request.urlopen(request, timeout=30) as response:
                return json.load(response)
        except (OSError, ValueError):
            if attempt == 5:
                raise
            time.sleep(2 ** attempt)


if __name__ == "__main__":
    main()
