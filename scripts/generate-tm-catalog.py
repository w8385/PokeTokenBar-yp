#!/usr/bin/env python3
"""Generate Sources/PokeTokenBar/Core/MachineCatalogTable.swift from PokéAPI.

Run when a new generation lands and commit the result; the app never fetches TM data at runtime.

    python3 -I scripts/generate-tm-catalog.py [--out PATH]

A move is in the catalog when it is battle-usable (damaging or weather-setting) and at least one species
learns it by machine. "Learns by machine" uses the bot's own rule, `ypoke.pokeapi.learnset_from`: the
newest main-series version group that has level-up moves for that species.
"""
import argparse
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "bot"))
from ypoke.pokeapi import API_BASE, WEATHER_MOVES, _get_json, learnset_from  # noqa: E402

MAX_SPECIES = 1025
WORKERS = 4
OUT = ROOT / "Sources/PokeTokenBar/Core/MachineCatalogTable.swift"


def get(url: str) -> dict:
    for attempt in range(1, 5):
        try:
            return _get_json(url)
        except OSError:
            if attempt == 4:
                raise
            time.sleep(2 * attempt)
    raise AssertionError("unreachable")


def machine_moves(species_id: int) -> list[int]:
    learnset = learnset_from(get(f"{API_BASE}/pokemon/{species_id}"))
    return [entry["move_id"] for entry in learnset if entry["source"] == "machine"]


def move_row(move_id: int) -> str | None:
    move = get(f"{API_BASE}/move/{move_id}")
    weather = WEATHER_MOVES.get(move_id, "")
    power = move["power"] or 0
    if not weather and not (power and move["damage_class"]["name"] != "status"):
        return None
    names = {entry["language"]["name"]: entry["name"] for entry in move["names"]}
    en = names.get("en", move["name"])
    ko = names.get("ko", en)
    ja = names.get("ja-hrkt") or names.get("ja") or en
    return "|".join([str(move_id), move["type"]["name"], str(power), weather, ko, en, ja])


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=OUT)
    out = parser.parse_args().out

    with ThreadPoolExecutor(max_workers=WORKERS) as pool:
        by_species = dict(zip(range(1, MAX_SPECIES + 1), pool.map(machine_moves, range(1, MAX_SPECIES + 1))))
        move_ids = sorted({move_id for moves in by_species.values() for move_id in moves})
        rows = dict(zip(move_ids, pool.map(move_row, move_ids)))

    usable = {move_id for move_id, row in rows.items() if row}
    learners = [f"{species}:{','.join(str(m) for m in sorted(set(moves) & usable))}"
                for species, moves in by_species.items() if set(moves) & usable]
    table = "\n".join(rows[move_id] for move_id in sorted(usable))
    out.write_text(
        "// Generated by scripts/generate-tm-catalog.py; do not edit.\n\n"
        "/// Every battle-usable TM move, and which species learn it by machine.\n"
        "enum MachineCatalogTable {\n"
        "    /// `id|type|power|weather|ko|en|ja`, one move per line.\n"
        f'    static let moves = """\n{table}\n"""\n\n'
        "    /// `speciesID:moveID,moveID,…`, one species per line.\n"
        f'    static let learners = """\n{chr(10).join(learners)}\n"""\n'
        "}\n"
    )
    print(f"{len(usable)} moves, {len(learners)} species -> {out}", file=sys.stderr)


if __name__ == "__main__":
    main()
