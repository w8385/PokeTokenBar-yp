#!/usr/bin/env python3
"""Generate Sources/PokeTokenBar/Core/EggMoveTable.swift from PokéAPI.

Run when a new generation lands and commit the result.

    python3 -I scripts/generate-egg-move-table.py [--out PATH]

A species is listed when the bot's `GET /v1/moves?egg=1` would give it at least one attacking egg move: a damaging or
weather-setting egg move of the species or any species it evolved from, by the bot's own rules
(`ypoke.pokeapi.egg_moves_from` and `_ancestors`).
"""
import argparse
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "bot"))
from ypoke.move_effects import STATUS_MOVES  # noqa: E402
from ypoke.pokeapi import API_BASE, WEATHER_MOVES, _ancestors, _get_json, egg_moves_from  # noqa: E402

MAX_SPECIES = 1025
WORKERS = 4
OUT = ROOT / "Sources/PokeTokenBar/Core/EggMoveTable.swift"


def get(url: str) -> dict:
    for attempt in range(1, 5):
        try:
            return _get_json(url)
        except OSError:
            if attempt == 4:
                raise
            time.sleep(2 * attempt)
    raise AssertionError("unreachable")


def egg_moves(species_id: int) -> list[int]:
    return egg_moves_from(get(f"{API_BASE}/pokemon/{species_id}"))


def is_attacking(move_id: int) -> bool:
    if move_id in STATUS_MOVES:
        return False
    move = get(f"{API_BASE}/move/{move_id}")
    return move_id in WEATHER_MOVES or bool(move["power"] and move["damage_class"]["name"] != "status")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=OUT)
    out = parser.parse_args().out

    species = range(1, MAX_SPECIES + 1)
    with ThreadPoolExecutor(max_workers=WORKERS) as pool:
        own = dict(zip(species, pool.map(egg_moves, species)))
        move_ids = sorted({move_id for moves in own.values() for move_id in moves})
        attacking = {move_id for move_id, keep in zip(move_ids, pool.map(is_attacking, move_ids)) if keep}

    def has_attacking_egg_move(species_id: int) -> bool:
        return any(set(own.get(member, ())) & attacking for member in (species_id, *_ancestors(species_id)))

    eligible = [species_id for species_id in species if has_attacking_egg_move(species_id)]
    lines = [",".join(str(species_id) for species_id in eligible[start:start + 20])
             for start in range(0, len(eligible), 20)]
    out.write_text(
        "// Generated by scripts/generate-egg-move-table.py; do not edit.\n\n"
        "/// Species the bot gives at least one attacking egg move, their own or one of a species they evolved from.\n"
        "enum EggMoveTable {\n"
        f'    static let speciesWithAttackingEggMoves = """\n{(",{}".format(chr(10))).join(lines)}\n"""\n'
        "}\n"
    )
    print(f"{len(eligible)} species, {len(attacking)} attacking egg moves -> {out}", file=sys.stderr)


if __name__ == "__main__":
    main()
