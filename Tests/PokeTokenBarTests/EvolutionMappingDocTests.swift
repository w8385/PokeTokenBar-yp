import XCTest
@testable import PokeTokenBar

/// `docs/reference/evolution-mapping.md` is generated from the rule table and the PokéAPI fixture, so it cannot
/// drift. Regenerate with `PTB_WRITE_EVOLUTION_DOC=1 swift test --filter EvolutionMappingDocTests`.
final class EvolutionMappingDocTests: XCTestCase {
    private let extraNames = [223: "Remoraid", 625: "Bisharp"]

    private struct Step {
        let species: Int
        let name: String
        let signatures: [String]
    }

    private func pretty(_ slug: String) -> String {
        slug.split(separator: "-").map { $0.capitalized }.joined(separator: " ")
    }

    private func loadSteps() throws -> [(step: Step, hasDetails: Bool)] {
        let url = URL(fileURLWithPath: #filePath).deletingLastPathComponent()
            .appendingPathComponent("Fixtures/evolution-steps.json")
        let raw = try JSONSerialization.jsonObject(with: Data(contentsOf: url)) as? [[String: Any]] ?? []
        return raw.map { entry in
            let details = entry["details"] as? [[String: Any]] ?? []
            let signatures = details.map {
                EvolutionRules.signature(trigger: $0["trigger"] as? String ?? "", keys: Set($0.keys),
                                         item: $0["item"] as? String)
            }
            let gated = signatures.contains { $0 == nil } ? [] : signatures.compactMap { $0 }
            return (Step(species: entry["species"] as? Int ?? 0, name: pretty(entry["name"] as? String ?? ""),
                         signatures: gated), !details.isEmpty)
        }
    }

    private func render() throws -> String {
        let steps = try loadSteps()
        let names = Dictionary(uniqueKeysWithValues: steps.map { ($0.step.species, $0.step.name) })
            .merging(extraNames) { fixture, _ in fixture }
        let l = L(.en)
        func name(_ id: Int) -> String { names[id] ?? "#\(id)" }

        var mapped = 0, pending = 0, found = 0
        var rows: [String] = []
        for (step, _) in steps where !step.signatures.isEmpty {
            let rule = EvolutionRules.rule(for: step.species)
            let covered = step.signatures.filter { rule?.covers.contains($0) == true }
            let deferred = step.signatures.filter { signature in
                rule?.covers.contains(signature) != true
                    && EvolutionRules.deferredSignaturePrefixes.contains { signature.hasPrefix($0) }
            }
            found += step.signatures.count
            mapped += covered.count
            pending += deferred.count
            guard let rule else {
                rows.append("| \(name(step.species)) (#\(step.species)) | \(step.signatures.joined(separator: "; ")) | Trade evolutions arrive with the trade commit | Pending |")
                continue
            }
            let original = rule.original.map { l.evolutionOriginalText($0, speciesName: name) }.joined(separator: "; ")
            var app: [String] = []
            if let selector = rule.selector { app.append(l.evolutionSelectorText(selector)) }
            if !rule.paths.isEmpty {
                app.append(rule.paths.map { l.evolutionPathText($0, speciesName: name) }.joined(separator: " **or** "))
            }
            let status = rule.formNotShown ? "Mapped (form not drawn in the dex)" : (deferred.isEmpty ? "Mapped" : "Pending")
            rows.append("| \(name(step.species)) (#\(step.species)) | \(original) | \(app.joined(separator: ". ")) | \(status) |")
        }
        let unconditional = EvolutionRules.unconditional.sorted().map { "\(name($0)) (#\($0))" }.joined(separator: ", ")

        return """
        # Evolution mapping

        Generated by `EvolutionMappingDocTests` from `Sources/PokeTokenBar/Core/EvolutionRuleTable.swift` and the
        PokéAPI snapshot `Tests/PokeTokenBarTests/Fixtures/evolution-steps.json`. Do not edit by hand.

        Every evolution step that is not a plain level or a stone has an app-native condition. All species stay
        reachable: steps that depend on something outside the app (rain, battles) also open once the growth bar
        has filled to 200%, and no step needs an item that cannot be bought or earned.

        **Special steps found: \(found). Mapped: \(mapped). Pending: \(pending).**

        Steps the games list with no condition at all keep growing by XP: \(unconditional).

        | Evolves into | In the games | In this app | Status |
        |---|---|---|---|
        \(rows.joined(separator: "\n"))

        """
    }

    func testMappingDocMatchesTheRuleTable() throws {
        let doc = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
            .deletingLastPathComponent().appendingPathComponent("docs/reference/evolution-mapping.md")
        let text = try render()
        if ProcessInfo.processInfo.environment["PTB_WRITE_EVOLUTION_DOC"] == "1" {
            try text.write(to: doc, atomically: true, encoding: .utf8)
        }
        XCTAssertEqual(try String(contentsOf: doc, encoding: .utf8), text,
                       "run with PTB_WRITE_EVOLUTION_DOC=1 to regenerate")
    }
}
